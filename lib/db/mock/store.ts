/**
 * In-memory data store backing demo mode.
 *
 * The fixture is a real trip exported from Postgres (a two-city Greece trip
 * with a full generated itinerary), so the demo exercises the same shapes the
 * production queries return — including the multi-city leg/flight/stay model.
 *
 * Module-scoped and mutable: writes made during a demo session are visible for
 * the life of the server process and reset on restart. That is intentional —
 * a demo should be reproducible, and nothing here is meant to persist.
 */

import fixture from "./fixture.json";
import { sumActivityCosts, roundMoney } from "@/lib/planner/costs";
import { legForDate } from "@/lib/planner/legs";
import type {
  Trip,
  TripLeg,
  TripBrief,
  Booking,
  Itinerary,
  ItineraryDay,
  Activity,
  CommunityPost,
  PlaceReview,
  PreferenceProfile,
  ChangeLogEntry,
  TripFlight,
  TripAccommodation,
} from "@/lib/types";

interface MockTables {
  trips: Trip[];
  trip_legs: TripLeg[];
  trip_briefs: TripBrief[];
  bookings: Booking[];
  itineraries: Itinerary[];
  itinerary_days: ItineraryDay[];
  activities: Activity[];
  trip_flights: TripFlight[];
  trip_accommodations: TripAccommodation[];
  community_posts: CommunityPost[];
  place_reviews: PlaceReview[];
  preference_profiles: PreferenceProfile[];
  change_log: ChangeLogEntry[];
}

function seed(): MockTables {
  // Deep clone so mutations never write back through the imported JSON module,
  // which Node caches and shares across every import site.
  const f = structuredClone(fixture) as unknown as Record<string, unknown>;

  // The fixture is generated by exporting real rows, and a failed export writes
  // an error object rather than an array. Coercing here turns that into an
  // empty table instead of a "filter is not a function" crash deep in a route.
  const table = <T>(name: string): T[] => {
    const value = f[name];
    if (Array.isArray(value)) return value as T[];
    if (value !== undefined) {
      console.warn(
        `[demo] fixture table "${name}" is not an array — treating it as empty.`
      );
    }
    return [];
  };

  const days = table<ItineraryDay>("itinerary_days");
  const activities = table<Activity>("activities");
  const itineraries = table<Itinerary>("itineraries");

  // The exported fixture carries the model's own arithmetic, which disagreed with
  // its activities (a day stored as $480 whose activities sum to $105). Re-derive
  // so the demo starts from the same invariant the live code maintains.
  for (const d of days) {
    d.daily_cost = sumActivityCosts(activities.filter((a) => a.day_id === d.day_id));
  }
  // The exported fixture put the Paros -> Athens transfer day (27 Aug) under
  // Paros. The product convention is that a transfer day belongs to the city
  // being travelled TO (see legForDate / createItineraryFromLLMOutput).
  const legs = table<TripLeg>("trip_legs");
  const tripIdOf = new Map(itineraries.map((it) => [it.itinerary_id, it.trip_id]));
  for (const d of days) {
    const tripLegs = legs.filter((l) => l.trip_id === tripIdOf.get(d.itinerary_id));
    const leg = legForDate(
      d.date,
      tripLegs.map((l) => ({ ...l, arrival_date: l.arrival_date, departure_date: l.departure_date }))
    );
    if (leg && tripLegs.length > 1) d.leg_id = leg.leg_id;
  }
  for (const it of itineraries) {
    it.total_cost_estimate = roundMoney(
      days
        .filter((d) => d.itinerary_id === it.itinerary_id)
        .reduce((sum, d) => sum + (d.daily_cost ?? 0), 0)
    );
  }

  return {
    trips: table<Trip>("trips"),
    trip_legs: table<TripLeg>("trip_legs"),
    trip_briefs: table<TripBrief>("trip_briefs"),
    bookings: table<Booking>("bookings"),
    itineraries,
    itinerary_days: days,
    activities,
    trip_flights: table<TripFlight>("trip_flights"),
    trip_accommodations: table<TripAccommodation>("trip_accommodations"),
    community_posts: table<CommunityPost>("community_posts"),
    place_reviews: [],
    preference_profiles: [],
    change_log: [],
  };
}

/**
 * Survives Next.js dev-server hot reloads, which re-evaluate modules and would
 * otherwise discard everything the user did mid-demo.
 */
const globalStore = globalThis as unknown as { __mockDb?: MockTables };
export const db: MockTables = (globalStore.__mockDb ??= seed());

/** Restores the fixture, discarding demo-session writes. */
export function resetStore(): void {
  globalStore.__mockDb = seed();
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

export function newId(): string {
  return crypto.randomUUID();
}

export function nowIso(): string {
  return new Date().toISOString();
}

/** Returns a copy so callers can never mutate stored rows by reference. */
export function clone<T>(row: T): T {
  return structuredClone(row);
}

export function cloneAll<T>(rows: T[]): T[] {
  return rows.map((r) => structuredClone(r));
}

/**
 * Sorts by date-like string ascending, then by a numeric tiebreaker.
 * Mirrors the ordering the Postgres queries apply.
 */
export function byDateThen<T>(
  rows: T[],
  date: (r: T) => string | null,
  tiebreak: (r: T) => number
): T[] {
  return [...rows].sort((a, b) => {
    const da = date(a) ?? "";
    const dbb = date(b) ?? "";
    if (da !== dbb) return da < dbb ? -1 : 1;
    return tiebreak(a) - tiebreak(b);
  });
}
